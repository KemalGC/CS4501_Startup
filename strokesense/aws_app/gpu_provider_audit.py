"""Audit ONNX Runtime profiling events for the pinned CUDA pose model.

A CUDA EP in get_providers() alone is insufficient: ONNX Runtime may silently
assign graph nodes to CPU. Inspect measured node events after real inference.
The input is the profiling file generated by our own model session, not user data.
"""
from __future__ import annotations

import json
from pathlib import Path

from .gpu_preflight import GpuPreflightError

# These operations are structural bookkeeping; allowing them on CPU does not
# authorize CPU execution of the pose network's convolutions.
CPU_STRUCTURAL_OPS = frozenset({
    "Shape", "Size", "Gather", "GatherElements", "GatherND", "Unsqueeze",
    "Squeeze", "Concat", "Reshape", "Slice", "Cast", "ConstantOfShape",
    "Expand", "Range", "NonZero", "Flatten", "Identity", "Transpose",
})


def audit_cuda_profile(profile_path: str) -> dict[str, int]:
    path = Path(profile_path)
    if not profile_path or not path.is_file():
        raise GpuPreflightError("cuda_profile_missing")
    try:
        if path.stat().st_size > 40_000_000:
            raise GpuPreflightError("cuda_profile_too_large")
        with path.open(encoding="utf-8") as stream:
            events = json.load(stream)
        if not isinstance(events, list):
            raise GpuPreflightError("cuda_profile_invalid")
        cuda_nodes = cpu_nodes = cuda_conv_nodes = 0
        unsupported_cpu = set()
        for event in events:
            if not isinstance(event, dict) or event.get("cat") != "Node":
                continue
            args = event.get("args")
            if not isinstance(args, dict):
                continue
            provider, op = args.get("provider"), args.get("op_name")
            if provider == "CUDAExecutionProvider":
                cuda_nodes += 1
                if op == "Conv":
                    cuda_conv_nodes += 1
            elif provider == "CPUExecutionProvider":
                cpu_nodes += 1
                if op not in CPU_STRUCTURAL_OPS:
                    unsupported_cpu.add(str(op)[:80])
            else:
                raise GpuPreflightError("unexpected_execution_provider")
        if unsupported_cpu:
            # Do not leak model paths or media: report only the bounded op names.
            raise GpuPreflightError("cuda_cpu_compute_fallback",
                                    diagnostics={"cpu_ops": sorted(unsupported_cpu)[:10]})
        if cuda_nodes < 1 or cuda_conv_nodes < 1:
            raise GpuPreflightError("cuda_kernels_not_verified")
        return {"cuda_nodes": cuda_nodes, "cuda_conv_nodes": cuda_conv_nodes,
                "cpu_structural_nodes": cpu_nodes}
    except (OSError, ValueError, TypeError) as exc:
        raise GpuPreflightError("cuda_profile_invalid") from exc
    finally:
        path.unlink(missing_ok=True)
